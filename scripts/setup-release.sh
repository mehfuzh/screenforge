#!/usr/bin/env bash
# Configure signed + notarized releases (Developer ID, no App Store needed).
#
#   scripts/setup-release.sh            # verify notarytool credentials with Apple and store them
#                                       # in the keychain; releases then run from this Mac with
#                                       # scripts/release.sh (no certificate export, no prompts)
#   scripts/setup-release.sh --ci       # additionally export the certificate and set the GitHub
#                                       # secrets so .github/workflows/release.yml can build on
#                                       # Actions (macOS asks to allow key access per identity)
#   scripts/setup-release.sh --public   # … and make the repo public (needed for public downloads)
#
# Needs: the "Developer ID Application" certificate in the login keychain (it is), gh (logged in),
# Xcode command line tools. The app-specific password cannot be generated by a script; create one
# at https://account.apple.com/account/manage and paste it at the prompt, or pass it in the
# environment:  APPLE_ID=you@example.com APPLE_APP_SPECIFIC_PASSWORD=xxxx-xxxx-xxxx-xxxx scripts/setup-release.sh
# With --ci, export the Developer ID certificate from Keychain Access as a .p12 first and pass
# APPLE_CERTIFICATE_P12=~/Desktop/devid.p12 APPLE_CERTIFICATE_PASSWORD=<its password> (or answer the prompts).
set -euo pipefail
cd "$(dirname "$0")/.."

REPO=${REPO:-mehfuzh/screenforge}
PUBLIC=0; TAG=""; CI=0
while [ $# -gt 0 ]; do
  case "$1" in
    --public) PUBLIC=1 ;;
    --ci) CI=1 ;;
    --tag) TAG=$2; shift ;;
    *) echo "unknown option $1"; exit 1 ;;
  esac
  shift
done
for t in gh security xcrun base64; do command -v $t >/dev/null || { echo "missing: $t"; exit 1; }; done

echo "→ Developer ID certificate"
IDENTITY=$(security find-identity -v -p codesigning | grep "Developer ID Application" | head -1 | sed -E 's/.*"(.*)".*/\1/')
[ -n "$IDENTITY" ] || { echo "no Developer ID Application certificate in the keychain. Create one at https://developer.apple.com/account/resources/certificates and install it, then rerun."; exit 1; }
TEAM_ID=$(echo "$IDENTITY" | sed -E 's/.*\(([A-Z0-9]+)\).*/\1/')
echo "  $IDENTITY (team $TEAM_ID)"

TMP=$(mktemp -d); chmod 700 "$TMP"; trap 'rm -rf "$TMP"' EXIT

echo "→ Notarization credentials"
DEFAULT_APPLE_ID=${APPLE_ID:-$(git config user.email 2>/dev/null || true)}
read -r -p "  Apple ID of the developer account [${DEFAULT_APPLE_ID}]: " APPLE_ID < /dev/tty
APPLE_ID=${APPLE_ID:-$DEFAULT_APPLE_ID}
echo "  You need an app-specific password: https://account.apple.com/account/manage"
echo "  (Sign-In and Security → App-Specific Passwords → '+', name it 'ScreenForge notarization')."
APP_PW=${APPLE_APP_SPECIFIC_PASSWORD:-}
if [ -n "$APP_PW" ]; then
  # given via the environment: store it non-interactively
  xcrun notarytool store-credentials "screenforge" --apple-id "$APPLE_ID" --password "$APP_PW" --team-id "$TEAM_ID"
else
  # notarytool asks for the password itself (typed or pasted; input is hidden) and validates it
  echo "  Paste the password at notarytool's prompt below; nothing is shown while you paste, press Return after."
  xcrun notarytool store-credentials "screenforge" --apple-id "$APPLE_ID" --team-id "$TEAM_ID" < /dev/tty
fi
echo "→ Checking the stored credentials with Apple's notary service"
if xcrun notarytool history --keychain-profile "screenforge" >/dev/null 2>"$TMP/notary.err"; then
  echo "  accepted; stored in the keychain as notarytool profile 'screenforge'"
else
  echo "  rejected:"; sed 's/^/    /' "$TMP/notary.err"
  echo "  Common causes: wrong Apple ID (use the developer account login, not an alias), a regular"
  echo "  password instead of an app-specific one, or the team $TEAM_ID not being on that Apple ID."
  exit 1
fi
# for --ci: the secrets need the raw password
if [ "$CI" = 1 ] && [ -z "$APP_PW" ]; then
  read -r -s -p "  For the GitHub secret, paste the same app-specific password again: " APP_PW < /dev/tty; echo
fi

if [ "$CI" = 1 ]; then
  # One .p12 with only the Developer ID identity (one keychain prompt). `security export` can't
  # filter by identity and would prompt once per private key in the keychain.
  P12=${APPLE_CERTIFICATE_P12:-}
  if [ -z "$P12" ]; then
    cat <<MSG
→ Export the certificate once from Keychain Access:
    1. Keychain Access → login → My Certificates
    2. right-click "$IDENTITY" → Export…
    3. save as ~/Desktop/devid.p12 and choose a password
MSG
    open -a "Keychain Access" 2>/dev/null || true
    read -r -p "  Path to the .p12 [~/Desktop/devid.p12]: " P12 < /dev/tty
    P12=${P12:-$HOME/Desktop/devid.p12}
  fi
  P12=${P12/#\~/$HOME}
  [ -s "$P12" ] || { echo "no .p12 at $P12"; exit 1; }
  P12_PASS=${APPLE_CERTIFICATE_PASSWORD:-}
  [ -n "$P12_PASS" ] || { read -r -s -p "  Password you set on the .p12: " P12_PASS < /dev/tty; echo; }
  # check the password and that the Developer ID identity is inside
  openssl pkcs12 -in "$P12" -passin "pass:$P12_PASS" -nokeys -legacy 2>/dev/null | grep -q "Developer ID Application" \
    || openssl pkcs12 -in "$P12" -passin "pass:$P12_PASS" -nokeys 2>/dev/null | grep -q "Developer ID Application" \
    || { echo "  could not open $P12 with that password, or it has no Developer ID Application certificate"; exit 1; }
  cp "$P12" "$TMP/identities.p12"
  echo "  ok: Developer ID identity found in $P12"
  echo "→ GitHub secrets on $REPO"
  gh secret set APPLE_CERTIFICATE_BASE64    -R "$REPO" --body "$(base64 -i "$TMP/identities.p12")"
  gh secret set APPLE_CERTIFICATE_PASSWORD  -R "$REPO" --body "$P12_PASS"
  gh secret set APPLE_ID                    -R "$REPO" --body "$APPLE_ID"
  gh secret set APPLE_APP_SPECIFIC_PASSWORD -R "$REPO" --body "$APP_PW"
  gh secret set APPLE_TEAM_ID               -R "$REPO" --body "$TEAM_ID"
  gh secret list -R "$REPO"
  echo "  Uploaded. Delete $P12 now that GitHub has it: rm \"$P12\""
fi

if [ "$PUBLIC" = 1 ]; then
  echo "→ Making $REPO public"
  gh repo edit "$REPO" --visibility public --accept-visibility-change-consequences
fi

if [ -n "$TAG" ]; then
  echo "→ Tagging $TAG and pushing (triggers .github/workflows/release.yml)"
  git tag "$TAG" && git push origin "$TAG"
  echo "  follow it with: gh run watch -R $REPO"
fi

cat <<MSG

Done. Publish a release from this Mac with:
  scripts/release.sh 0.1.0
It signs with "$IDENTITY", notarizes with the stored profile, staples, builds the DMG and
creates the GitHub Release. Downloads are public only once the repository is public
(run with --public, or gh repo edit … --visibility public).
MSG
